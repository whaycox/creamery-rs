use super::*;

pub const CARRIAGE_RETURN: u8 = 0x0D;
pub const LINE_FEED: u8 = 0x0A;
pub const SPACE: u8 = 0x20;
pub const HORIZONTAL_TAB: u8 = 0x09;
pub const DOUBLE_QUOTE: u8 = 0x22;

pub static NEW_LINE: [u8; 2] = [0x0D,0x0A];

pub fn controls() -> &'static HashSet<u8> { CONTROLS.get_or_init(build_controls) }
static CONTROLS: OnceLock<HashSet<u8>> = OnceLock::new();
fn build_controls() -> HashSet<u8> {
    vec![
        0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06,
        0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D,
        0x0E, 0x0F, 0x10, 0x11, 0x12, 0x13, 0x14,
        0x15, 0x16, 0x17, 0x18, 0x19, 0x1A, 0x1B,
        0x1C, 0x1D, 0x1E, 0x1F, 0x7F,
    ].into_iter().collect()
}

pub fn tspecials() -> &'static HashSet<u8> { TSPECIALS.get_or_init(build_tspecials) }
static TSPECIALS: OnceLock<HashSet<u8>> = OnceLock::new();
fn build_tspecials() -> HashSet<u8> {
    vec![
        0x28, 0x29, 0x3C, 0x3E, 0x40, 0x2C, 0x3B, 0x3A, 
        0x5C, 0x22, 0x2F, 0x5B, 0x5D, 0x3F, 0x3D, 0x7B, 
        0x7D, 0x20, 0x09,
    ].into_iter().collect()
}

pub fn qdtext_restrictions() -> &'static HashSet<u8> { QDTEXT_RESTRICTIONS.get_or_init(build_qdtext_restrictions) }
static QDTEXT_RESTRICTIONS: OnceLock<HashSet<u8>> = OnceLock::new();
fn build_qdtext_restrictions() -> HashSet<u8> {
    vec![
        0x28, 0x29, 0x3C, 0x3E, 0x40, 0x2C, 0x3B, 0x3A, 
        0x5C, 0x22, 0x2F, 0x5B, 0x5D, 0x3F, 0x3D, 0x7B, 
        0x7D, 0x20, 0x09,
    ].into_iter().collect()
}